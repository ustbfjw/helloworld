function rows=write_paired_velocity_diagnostics(outdir)
%WRITE_PAIRED_VELOCITY_DIAGNOSTICS 已保存视频bootstrap的事后配对速度诊断。
% schema1比较full与其余方法，schema2比较spatial_validated与其余方法。
% 不重抽样、不按真磁速度筛选、不设速度非劣界限，不修改原summary.mat。
source=fullfile(outdir,'summary.mat');
assert(exist(source,'file')==2,'缺少已完成的summary.mat。');
s=load(source,'report','bootstrap'); report=s.report; protocol=report.protocol;
schema=protocol.schema_version; assert(ismember(schema,[1 2]) && report.schema_version==schema);
if schema==1, primary='full'; else, primary='spatial_validated'; end
methods=cellstr(string(protocol.methods)); conditions={protocol.conditions.name};
primary_index=find(strcmp(methods,primary)); assert(isscalar(primary_index));
B=protocol.bootstrap_replicates;
assert(isscalar(B) && isfinite(B) && B>=1 && B==round(B));
summary=report.summary; rows=struct([]);
for ig=1:numel(protocol.groups)
    group=protocol.groups(ig).name;
    bg=find(cellfun(@(x)strcmp(x.group,group),s.bootstrap)); assert(isscalar(bg));
    draws=s.bootstrap{bg}.draws;
    expected=[B,numel(conditions),numel(methods)];
    assert(isequal(size(draws.u),expected) && isequal(size(draws.v),expected), ...
        '保存的速度bootstrap形状不符合协议。');
    for ic=1:numel(conditions)
        a=pick_row(summary,group,conditions{ic},primary);
        for im=setdiff(1:numel(methods),primary_index,'stable')
            b=pick_row(summary,group,conditions{ic},methods{im});
            assert(a.n_videos==b.n_videos);
            adequate=a.active_videos>=10 && b.active_videos>=10 && a.n_loc>=5000 && b.n_loc>=5000;
            [uc,un,us]=paired_interval(draws.u(:,ic,primary_index),draws.u(:,ic,im), ...
                a.flow_um_s,b.flow_um_s,a,b,adequate,B);
            [vc,vn,vs]=paired_interval(draws.v(:,ic,primary_index),draws.v(:,ic,im), ...
                a.magnetic_velocity_um_s,b.magnetic_velocity_um_s,a,b,adequate,B);
            row=struct('schema_version',schema,'group',group,'condition',conditions{ic}, ...
                'method',primary,'reference',methods{im},'n_videos',a.n_videos, ...
                'active_method',a.active_videos,'active_reference',b.active_videos, ...
                'selected_localizations_method',a.n_loc,'selected_localizations_reference',b.n_loc, ...
                'adequate_evidence',adequate,'bootstrap_replicates',B, ...
                'flow_method_um_s',a.flow_um_s,'flow_reference_um_s',b.flow_um_s, ...
                'delta_flow_um_s',a.flow_um_s-b.flow_um_s, ...
                'delta_flow_ci95_low',uc(1),'delta_flow_ci95_high',uc(2), ...
                'flow_paired_bootstrap_valid',un,'flow_status',us, ...
                'magnetic_velocity_method_um_s',a.magnetic_velocity_um_s, ...
                'magnetic_velocity_reference_um_s',b.magnetic_velocity_um_s, ...
                'delta_magnetic_velocity_um_s',a.magnetic_velocity_um_s-b.magnetic_velocity_um_s, ...
                'delta_magnetic_velocity_ci95_low',vc(1),'delta_magnetic_velocity_ci95_high',vc(2), ...
                'magnetic_velocity_paired_bootstrap_valid',vn,'magnetic_velocity_status',vs, ...
                'truth_velocity_method_um_s',a.truth_velocity_um_s, ...
                'truth_velocity_reference_um_s',b.truth_velocity_um_s, ...
                'magnetic_velocity_error_method_um_s',a.magnetic_velocity_um_s-a.truth_velocity_um_s, ...
                'magnetic_velocity_error_reference_um_s',b.magnetic_velocity_um_s-b.truth_velocity_um_s);
            if isempty(rows), rows=row; else, rows(end+1)=row; end %#ok<AGROW>
        end
    end
end
writetable(struct2table(rows),fullfile(outdir,'paired_velocity.csv'));
provenance=struct('analysis','post-hoc paired velocity diagnostics from saved video bootstrap', ...
    'schema_version',schema,'source_summary',source,'source_summary_sha256',targeted_sha256(source), ...
    'source_protocol_hash',report.protocol_hash,'helper_file',mfilename('fullpath'), ...
    'helper_sha256',targeted_sha256([mfilename('fullpath') '.m']), ...
    'generated_at',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss Z')), ...
    'matlab_version',version,'rows',numel(rows),'primary_method',primary, ...
    'difference_definition','method minus reference, um/s', ...
    'interval_definition','paired saved video-bootstrap differences; percentile 2.5 and 97.5; pointwise exploratory', ...
    'availability_rule','both active videos >=4 and finite paired replicates >=95%; adequate separately requires >=10 active videos and >=5000 localizations in both methods', ...
    'limitation','No prespecified velocity margin; no noninferiority/equivalence or preservation claim. Truth speed is diagnostic only and never selects replicates.', ...
    'original_summary_unchanged',true);
fid=fopen(fullfile(outdir,'paired_velocity_provenance.json'),'w','n','UTF-8'); assert(fid>=0);
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(provenance,PrettyPrint=true));
fprintf('paired velocity diagnostics: schema%d, %d rows; no velocity preservation margin.\n',schema,numel(rows));
end

function row=pick_row(summary,group,condition,method)
idx=find(strcmp({summary.group},group) & strcmp({summary.condition},condition) & strcmp({summary.method},method));
assert(isscalar(idx),'汇总行不存在或重复。'); row=summary(idx);
end

function [ci,n,status]=paired_interval(a,b,point_a,point_b,row_a,row_b,adequate,B)
good=isfinite(a) & isfinite(b); n=sum(good); ci=[NaN NaN];
if ~row_a.waveform_identifiable || ~row_b.waveform_identifiable || ~isfinite(point_a) || ~isfinite(point_b)
    status='unidentifiable_or_nonfinite_point_estimate';
elseif min(row_a.active_videos,row_b.active_videos)<4
    status='descriptive_only_fewer_than_4_active_videos';
elseif n<0.95*B
    status='insufficient_valid_paired_bootstrap';
else
    x=sort(a(good)-b(good)); pos=1+(numel(x)-1)*[0.025 0.975];
    lo=floor(pos); hi=ceil(pos); ci=x(lo)'.*(hi-pos)+x(hi)'.*(pos-lo);
    same=lo==hi; ci(same)=x(lo(same));
    if adequate, status='exploratory_pointwise_interval_available';
    else, status='exploratory_interval_available_low_information'; end
end
end
